// Build-time compilation allows a strict browser CSP without unsafe-eval.
import { readFileSync, writeFileSync } from 'node:fs';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { fullFormats } from 'ajv-formats/dist/formats.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import standalone from 'ajv/dist/standalone/index.js';
const ajv = new Ajv2020({ allErrors: true, strict: true, formats: fullFormats, code: { source: true, esm: true, formats: _`require("ajv-formats/dist/formats").fullFormats` } });
for (const [key, name] of [['inventory', 'inventory'], ['index', 'box-index']]) {
  ajv.addSchema(JSON.parse(readFileSync(new URL(`../schemas/v1/${name}.schema.json`, import.meta.url))), key);
}
let code = standalone(ajv, { inventory: 'inventory', index: 'index' });
const modules = new Map();
code = code.replace(/require\("([^"]+)"\)(\.default)?/g, (_, name, defaultExport) => {
  if (!modules.has(name)) modules.set(name, `runtime${modules.size}`);
  const binding = modules.get(name);
  return defaultExport ? `(${binding}.default ?? ${binding})` : binding;
});
code = '// Generated by tools/build_web_validators.mjs; do not edit.\n' + [...modules].map(([name, binding]) => `import ${binding} from ${JSON.stringify(name.endsWith('.js') ? name : `${name}.js`)};\n`).join('') + code + '\n';
const destination = new URL('../frontend/src/generated/validators.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== code) throw new Error('Browser validators are stale; run npm run build:web-validators');
} else writeFileSync(destination, code);
